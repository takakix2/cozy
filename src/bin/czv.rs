//! `czv` —— cozy の閲覧面（ページャー）。
//!
//! ⭐ **`cozy` と同じクレートから焼かれる 2 本目のバイナリ。**
//! 中身はライブラリを閲覧モードで呼ぶだけで、固有のロジックは持たない。
//!
//! # なぜ別名のコマンドなのか（`#14`）
//!
//! - **`cozy view <file>` ではない** —— 打鍵数が多い。⭐ そして `$PAGER` は
//!   引数付きの値を素朴に split しない実装で壊れるので、**裸の名前が要る**。
//! - **argv[0] を見る symlink ではない** —— `cargo install` は symlink を作らないので
//!   **経路によって在ったり無かったりする**。⚠️ cozy は設定について利用者に一手も
//!   要求していない道具なので、コマンド名でそれをやらせない。
//! - **隣の `cozy` を `exec` する薄い殻でもない** —— 11M を節約できるが、
//!   隣接への依存・新しい壊れ方・引数解析の新設、の 3 つを持ち込む。
//!
//! 📌 ∴ `[[bin]]` 2 本（11M → 22M）。同じコードを 2 度運ぶ分は、
//! **どの入れ方でも確実に在る**ことの対価として払う。

/// ⚠️ **`io::Result` をそのまま返さない** —— Rust の既定は `Error: Custom { kind: …, error: "…" }`
/// と Debug 形で出す。`less` と同じく `czv: missing filename` の 1 行で、終了コード 1 で終わる（`#19`）。
fn main() {
    if let Err(e) = cozy::run_cli_view_from_env() {
        eprintln!("czv: {e}");
        std::process::exit(1);
    }
}
